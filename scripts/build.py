#!/usr/bin/env python3
"""Build the final Kong config from team files + platform policy.

Developer teams own teams/<team>/*.yaml: services and routes only.
The platform team owns platform/: plugin profiles, global plugins, consumers.
Routes are private by default; only the tag 'access:public' opts out.
"""
import glob
import os
import sys

import yaml

ALLOWED_TOP = {"_format_version", "services"}
ALLOWED_ACCESS = {"access:public"}
FORBIDDEN = {"plugins", "consumers"}

errors = []


def fail(path, msg):
    errors.append(f"{path}: {msg}")


def load(path):
    with open(path) as f:
        return yaml.safe_load(f) or {}


def guard(path, doc):
    for key in doc:
        if key not in ALLOWED_TOP:
            fail(path, f"top-level '{key}' is not allowed in team files")
    for svc in doc.get("services", []):
        name = svc.get("name", "?")
        for key in FORBIDDEN & svc.keys():
            fail(path, f"service '{name}': '{key}' is owned by the platform team")
        for route in svc.get("routes", []):
            rname = route.get("name", "?")
            for key in FORBIDDEN & route.keys():
                fail(path, f"route '{rname}': '{key}' is owned by the platform team")
            for tag in route.get("tags", []):
                if tag.startswith("access:") and tag not in ALLOWED_ACCESS:
                    fail(path, f"route '{rname}': unknown access tag '{tag}'")


def main(out_path):
    policy = load("platform/profiles.yaml")
    consumers = load("platform/consumers.yaml").get("consumers", [])
    profiles = policy["profiles"]

    services, seen = [], {}
    for path in sorted(glob.glob("teams/*/*.yaml")):
        team = path.split(os.sep)[1]
        doc = load(path)
        guard(path, doc)
        for svc in doc.get("services", []):
            for obj in [svc] + svc.get("routes", []):
                key = obj.get("name")
                if key in seen:
                    fail(path, f"name '{key}' already used in {seen[key]}")
                seen[key] = path
            svc.setdefault("tags", []).append(f"team:{team}")
            for route in svc.get("routes", []):
                tags = route.setdefault("tags", [])
                profile = "public" if "access:public" in tags else "private"
                tags.append(f"team:{team}")
                route["plugins"] = [dict(p) for p in profiles[profile]]
            services.append(svc)

    if errors:
        print("Guard failed:", *errors, sep="\n  ")
        sys.exit(1)

    out = {
        "_format_version": "3.0",
        "services": services,
        "plugins": policy.get("global_plugins", []),
        "consumers": consumers,
    }
    os.makedirs(os.path.dirname(out_path), exist_ok=True)
    with open(out_path, "w") as f:
        f.write("# GENERATED by scripts/build.py — do not edit\n")
        yaml.safe_dump(out, f, sort_keys=False)
    print(f"Built {out_path}: {len(services)} services")


if __name__ == "__main__":
    main(sys.argv[1] if len(sys.argv) > 1 else "build/kong.yaml")